let obj = {
    name:"abhishek",
    age:24,
    gender: "male"
}

//object.keys() = returns the array of keys
let keys = Object.keys(obj);
console.log(keys);

//Object.values() = returns the array of values
let values = Object.values(obj);
console.log(values);

//Object.entries() = returns the array of key value pairs both.
let both = Object.entries(obj);
console.log(both);

